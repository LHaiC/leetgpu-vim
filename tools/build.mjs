#!/usr/bin/env node
/**
 * Packages the extension into dist/leetgpu-vim-<version>.zip.
 *
 * The zip is what users download from a GitHub release; Chrome has no
 * "install from zip" flow, so the instructions are: unzip, then load the
 * unzipped folder as an unpacked extension (see INSTALL.md).
 *
 * No npm dependencies: the archive is written with a small deterministic ZIP
 * writer (sorted entries, fixed 1980-01-01 timestamps, deflate where it helps),
 * so the same tree always produces byte-identical output.
 *
 * Usage:
 *   node tools/build.mjs
 *   node tools/build.mjs --expect-tag v1.0.0   # fail unless the tag matches manifest.version
 */
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { deflateRawSync } from "node:zlib";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

/** Files and folders that make up the shipped extension. */
const SHIPPED = ["manifest.json", "LICENSE", "README.md", "INSTALL.md", "icons", "src", "vendor"];

/** Markers that must be present in the vendored bundle (see tools/vendor.mjs). */
const VENDOR_BANNER = "Generated by tools/vendor.mjs";
const VENDOR_PATCH_MARK = "Patched by tools/vendor.mjs";

function fail(message) {
  console.error(`build: ${message}`);
  process.exit(1);
}

function collectFiles(entry) {
  const absolute = join(ROOT, entry);
  if (statSync(absolute).isDirectory()) {
    return readdirSync(absolute)
      .flatMap((child) => collectFiles(join(entry, child)))
      .sort();
  }
  return [entry];
}

function assertVendoredBundle() {
  const bundle = readFileSync(join(ROOT, "vendor/monaco-vim.js"), "utf8");
  if (!bundle.includes(VENDOR_BANNER) || !bundle.includes(VENDOR_PATCH_MARK)) {
    fail("vendor/monaco-vim.js is not the patched bundle — run: node tools/vendor.mjs");
  }
}

const CRC_TABLE = (() => {
  const table = new Int32Array(256);
  for (let index = 0; index < 256; index += 1) {
    let value = index;
    for (let bit = 0; bit < 8; bit += 1) {
      value = value & 1 ? 0xedb88320 ^ (value >>> 1) : value >>> 1;
    }
    table[index] = value;
  }
  return table;
})();

function crc32(buffer) {
  let crc = -1;
  for (let index = 0; index < buffer.length; index += 1) {
    crc = (crc >>> 8) ^ CRC_TABLE[(crc ^ buffer[index]) & 0xff];
  }
  return (crc ^ -1) >>> 0;
}

const DOS_TIME = 0; // 00:00:00
const DOS_DATE = (1 << 5) | 1; // 1980-01-01

function zipArchive(entries) {
  const parts = [];
  const directory = [];
  let offset = 0;

  for (const { name, data } of entries) {
    const nameBytes = Buffer.from(name, "utf8");
    const crc = crc32(data);
    const deflated = deflateRawSync(data, { level: 9 });
    const useDeflate = deflated.length < data.length;
    const payload = useDeflate ? deflated : data;
    const method = useDeflate ? 8 : 0;

    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0);
    local.writeUInt16LE(20, 4); // version needed
    local.writeUInt16LE(0, 6); // flags
    local.writeUInt16LE(method, 8);
    local.writeUInt16LE(DOS_TIME, 10);
    local.writeUInt16LE(DOS_DATE, 12);
    local.writeUInt32LE(crc, 14);
    local.writeUInt32LE(payload.length, 18);
    local.writeUInt32LE(data.length, 22);
    local.writeUInt16LE(nameBytes.length, 26);
    local.writeUInt16LE(0, 28); // extra length
    parts.push(local, nameBytes, payload);

    const head = Buffer.alloc(46);
    head.writeUInt32LE(0x02014b50, 0);
    head.writeUInt16LE(20, 4); // version made by
    head.writeUInt16LE(20, 6); // version needed
    head.writeUInt16LE(0, 8); // flags
    head.writeUInt16LE(method, 10);
    head.writeUInt16LE(DOS_TIME, 12);
    head.writeUInt16LE(DOS_DATE, 14);
    head.writeUInt32LE(crc, 16);
    head.writeUInt32LE(payload.length, 20);
    head.writeUInt32LE(data.length, 24);
    head.writeUInt16LE(nameBytes.length, 28);
    head.writeUInt16LE(0, 30); // extra
    head.writeUInt16LE(0, 32); // comment
    head.writeUInt16LE(0, 34); // disk number
    head.writeUInt16LE(0, 36); // internal attributes
    head.writeUInt32LE((0o100644 << 16) >>> 0, 38); // external attributes (unix mode)
    head.writeUInt32LE(offset, 42);
    directory.push(head, nameBytes);

    offset += local.length + nameBytes.length + payload.length;
  }

  const central = Buffer.concat(directory);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0);
  end.writeUInt16LE(0, 4);
  end.writeUInt16LE(0, 6);
  end.writeUInt16LE(entries.length, 8);
  end.writeUInt16LE(entries.length, 10);
  end.writeUInt32LE(central.length, 12);
  end.writeUInt32LE(offset, 16);
  end.writeUInt16LE(0, 20);
  return Buffer.concat([...parts, central, end]);
}

const manifest = JSON.parse(readFileSync(join(ROOT, "manifest.json"), "utf8"));
const expectedTag = process.argv[process.argv.indexOf("--expect-tag") + 1];
if (process.argv.includes("--expect-tag") && expectedTag !== `v${manifest.version}`) {
  fail(`git tag ${expectedTag} does not match manifest version ${manifest.version}`);
}

assertVendoredBundle();

const files = SHIPPED.flatMap(collectFiles).sort();
const archive = zipArchive(
  files.map((name) => ({ name, data: readFileSync(join(ROOT, name)) })),
);

const output = join(ROOT, "dist", `leetgpu-vim-${manifest.version}.zip`);
mkdirSync(dirname(output), { recursive: true });
writeFileSync(output, archive);

console.log(`build: ${relative(ROOT, output)} (${archive.length} bytes, ${files.length} files)`);
console.log(`build: sha256 ${createHash("sha256").update(archive).digest("hex")}`);
for (const name of files) console.log(`  ${name}`);
